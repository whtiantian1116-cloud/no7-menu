const rulesRoot = document.getElementById('rulesTranscription');
if (rulesRoot) {
  customerRules.forEach((section, sectionIndex) => {
    const group = document.createElement('section');
    group.className = 'rules-chapter';
    const heading = document.createElement('h3');
    heading.innerHTML = `<span>${String(sectionIndex + 1).padStart(2, '0')}</span>${section.title}<small>${section.en}</small>`;
    const list = document.createElement('ol');
    section.items.forEach((line) => {
      const item = document.createElement('li');
      item.textContent = line;
      list.appendChild(item);
    });
    group.append(heading, list);
    rulesRoot.appendChild(group);
  });
}
